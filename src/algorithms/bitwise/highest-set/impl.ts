// =============================================================================
// 最高设置位（Highest Set Bit / MSB）· 纯算法实现（零 DOM 依赖，可独立单测）
// 求整数二进制表示中「最高位的 1」的权值 2^floor(log2(x))。
// =============================================================================

/** 算法执行过程中的事件钩子。任一可选；实现录制器按需实现。 */
export interface HighestSetHooks {
  /** 每完成一次「向高位传播」后 x 的当前值（不断把低位填满 1）。 */
  onPropagate?: (step: number, v: number) => void;
}

/**
 * 最高设置位权值：返回 `2^k`，其中 k 是 x 最高位 1 的下标。
 *
 * 做法（不使用循环 / `Math.clz32`）：通过「自或右移」把最高位以下全部填成 1，
 * 然后 `(v >> 1) + 1` 得到只含最高位的 2 的幂。
 *
 * 1. `v |= v >> 1`、`v |= v >> 2`、`v |= v >> 4`、…、`v |= v >> 16`
 *    ——把从最高位起的所有低位都置 1（如 `0010...0` → `0011...1`）
 * 2. `(v >> 1) + 1`：右移一位去掉一个低位，再 +1 进回最高位 → `2^k`
 *
 * - `18 (10010)` → `4 (100)`
 * - `256` → `256`
 * - `x = 0` 时返回 0
 *
 * 仅用位运算，时间 `O(log 位宽) = O(1)`（5 次右移即覆盖 32 位）。
 *
 * @param x 输入非负整数
 * @param hooks 可选的事件钩子
 */
export function highestSet(x: number, hooks: HighestSetHooks = {}): number {
  let v = x | 0;
  if (v <= 0) {
    // 非正数：约定返回 0（无最高设置位）
    return v === 0 ? 0 : highestSet(~v + 1, hooks); // 负数取绝对值递归
  }
  const shifts = [1, 2, 4, 8, 16];
  shifts.forEach((s, i) => {
    v |= v >>> s;
    hooks.onPropagate?.(i, v);
  });
  return (v >>> 1) + 1;
}
