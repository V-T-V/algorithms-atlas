// =============================================================================
// 奇偶校验（Parity Check）· 纯算法实现（零 DOM 依赖，可独立单测）
// 统计整数二进制中 1 的个数奇偶：返回 0（偶）或 1（奇）。
// =============================================================================

/** 算法执行过程中的事件钩子。任一可选；实现录制器按需实现。 */
export interface ParityHooks {
  /** 每完成一次「折半异或」后 v 的当前值。 */
  onFold?: (step: number, v: number) => void;
}

/**
 * 计算奇偶校验位（1 的个数 mod 2）。
 *
 * 做法（折半异或，branchless）：不断把高位异或到低位，最终最低位即奇偶性。
 *
 * 1. `v ^= v >>> 16`
 * 2. `v ^= v >>> 8`
 * 3. `v ^= v >>> 4`
 * 4. `v ^= v >>> 2`
 * 5. `v ^= v >>> 1`
 *
 * 取 `v & 1` 即结果。原理：异或满足结合律，把上下半部分相消，递归到一位即得到全部位的异或和。
 *
 * - `7 (111)` → 3 个 1 → 奇 → 1
 * - `12 (1100)` → 2 个 1 → 偶 → 0
 *
 * 时间复杂度 `O(1)`（5 次折叠覆盖 32 位），空间 `O(1)`。
 *
 * @param x 输入整数
 * @param hooks 可选的事件钩子
 */
export function parity(x: number, hooks: ParityHooks = {}): number {
  let v = x | 0;
  const shifts = [16, 8, 4, 2, 1];
  shifts.forEach((s, i) => {
    v ^= v >>> s;
    hooks.onFold?.(i, v);
  });
  return v & 1;
}
